#!/usr/bin/env python3
"""ru_text.py — согласование русских числительных в выводе скриптов.

«1 картинка», «2 картинки», «5 картинок». Без этого сводка читается как машинный
вывод, а инструмент, который сам проверяет качество текста, тем более не имеет
права писать «Без адреса: 1 картинок».

    plural(n, "картинка", "картинки", "картинок")  -> "картинок"
    num(5, "картинка", "картинки", "картинок")     -> "5 картинок"

Только stdlib, без сети. Модуль держат отдельно от `http_safe.py`: тот про сеть,
и его тянут не все скрипты.
"""
from __future__ import annotations

__version__ = "0.1.0"


def plural(n, one: str, few: str, many: str) -> str:
    """Форма существительного при числе n: 1 — one, 2–4 — few, остальное — many.

    Дробное число («12.4 слова») всегда берёт форму few: при дроби существительное
    стоит в родительном падеже единственного числа, а это та же словоформа.
    """
    if isinstance(n, float):
        return few
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def num(n, one: str, few: str, many: str) -> str:
    """Число вместе с согласованным существительным: «21 картинка»."""
    return f"{n} {plural(n, one, few, many)}"
